using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Net;
using System.Text;

namespace IOptimizer.Tests
{
    // Saved outside bin/ so results remain easy to find after the test run.
    public sealed class ComparisonReport
    {
        private readonly Dictionary<string, Result> results = new Dictionary<string, Result>();
        public string Root { get; }

        public ComparisonReport()
        {
            var directory = new DirectoryInfo(AppDomain.CurrentDomain.BaseDirectory);
            while (directory != null && !File.Exists(Path.Combine(directory.FullName, "Image Optimizer.sln")))
                directory = directory.Parent;
            Root = Path.Combine(directory == null ? AppDomain.CurrentDomain.BaseDirectory
                : Path.Combine(directory.FullName, "IOptimizer.Tests"), "TestResults", "Comparisons");
            foreach (string folder in new[] { "original", "lossless", "lossy" })
                Directory.CreateDirectory(Path.Combine(Root, folder));
        }

        public void Add(string name, string source, bool lossy, CompressionResult compression, int changedPixels, int totalPixels)
        {
            lock (results)
            {
                string mode = lossy ? "lossy" : "lossless";
                File.Copy(source, Path.Combine(Root, "original", name), true);
                File.Copy(compression.ResultFileName, Path.Combine(Root, mode, name), true);
                results[name + "/" + mode] = new Result {
                    Name = name, Mode = mode, OriginalBytes = compression.OriginalFileSize,
                    ResultBytes = compression.ResultFileSize, ChangedPixels = changedPixels,
                    TotalPixels = totalPixels, Milliseconds = compression.Elapsed.TotalMilliseconds,
                };
                WriteReport();
            }
        }

        private void WriteReport()
        {
            var html = new StringBuilder(@"<!doctype html>
<html lang=""en""><meta charset=""utf-8""><meta name=""viewport"" content=""width=device-width,initial-scale=1"">
<title>Image Optimizer test comparisons</title>
<style>
body{font:16px/1.5 system-ui,sans-serif;margin:32px auto;max-width:1440px;padding:0 24px;color:#202733;background:#f4f6f9}
h1,h2,h3{line-height:1.2}h1{font-size:30px}h2{font-size:22px;margin-top:40px}h3{margin-top:0}a{color:#1558c0}
.grid{display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:16px}.card{padding:16px;border:1px solid #d3dae4;border-radius:8px;background:white}
.preview{display:flex;align-items:center;justify-content:center;min-height:260px;background:repeating-conic-gradient(#ddd 0% 25%,white 0% 50%) 50%/20px 20px}
img{max-width:100%;height:auto}dl{display:grid;grid-template-columns:1fr 1fr;gap:4px 12px;font-size:14px}dd{margin:0;text-align:right;font-variant-numeric:tabular-nums}
@media(max-width:800px){.grid{grid-template-columns:1fr}.preview{min-height:180px}}
</style><h1>Image Optimizer test comparisons</h1>
<p>Original files and the outputs produced by the bundled tools during this test run. Click an image to inspect its full resolution; GIFs animate.</p>
<p>Checkerboards show transparency. Changed pixels are counted after decoding, across every frame, including RGBA data under transparent pixels.
Lossless outputs should show zero changed pixels. Negative savings mean the output grew.</p>
<p><a href=""results.csv"">Download the size and pixel comparison data (CSV)</a></p>");
            html.Append("<p>Generated ").Append(DateTimeOffset.UtcNow.ToString("u", CultureInfo.InvariantCulture)).Append(" (UTC).</p>");
            var csv = new StringBuilder("File,Mode,OriginalBytes,ResultBytes,SavedBytes,SavingsPercent,ElapsedMilliseconds,ChangedPixels,TotalPixels\r\n");
            foreach (var group in results.Values.GroupBy(result => result.Name).OrderBy(group => group.Key))
            {
                Result example = group.First();
                html.Append("<section><h2>").Append(WebUtility.HtmlEncode(group.Key)).Append("</h2><div class=\"grid\">");
                AppendImage(html, "Original", "original/" + group.Key);
                html.Append("<dl><dt>Size</dt><dd>").Append(example.OriginalBytes.ToString("N0", CultureInfo.InvariantCulture)).Append(" bytes</dd></dl></article>");
                foreach (string mode in new[] { "lossless", "lossy" })
                {
                    Result result = group.SingleOrDefault(item => item.Mode == mode);
                    if (result == null)
                    {
                        html.Append("<article class=\"card\"><h3>").Append(mode).Append("</h3><p>Not generated by this test run.</p></article>");
                        continue;
                    }
                    AppendImage(html, mode == "lossy" ? "Lossy" : "Lossless", mode + "/" + result.Name);
                    html.AppendFormat(CultureInfo.InvariantCulture,
                        "<dl><dt>Size</dt><dd>{0:N0} bytes</dd><dt>Savings</dt><dd>{1:N1}% ({2:N0} bytes)</dd><dt>Changed pixels</dt><dd>{3:N0} / {4:N0}</dd><dt>Compression time</dt><dd>{5:N1} ms</dd></dl></article>",
                        result.ResultBytes, result.SavingsPercent, result.OriginalBytes - result.ResultBytes,
                        result.ChangedPixels, result.TotalPixels, result.Milliseconds);
                    csv.AppendFormat(CultureInfo.InvariantCulture, "\"{0}\",{1},{2},{3},{4},{5:F3},{6:F3},{7},{8}\r\n",
                        result.Name.Replace("\"", "\"\""), result.Mode, result.OriginalBytes, result.ResultBytes,
                        result.OriginalBytes - result.ResultBytes, result.SavingsPercent, result.Milliseconds,
                        result.ChangedPixels, result.TotalPixels);
                }
                html.Append("</div></section>");
            }
            html.Append("</html>");
            File.WriteAllText(Path.Combine(Root, "results.csv"), csv.ToString(), new UTF8Encoding(true));
            File.WriteAllText(Path.Combine(Root, "index.html"), html.ToString(), new UTF8Encoding(false));
        }

        private static void AppendImage(StringBuilder html, string label, string relativePath)
        {
            string url = WebUtility.HtmlEncode(relativePath);
            html.Append("<article class=\"card\"><h3>").Append(label).Append("</h3><div class=\"preview\"><a href=\"")
                .Append(url).Append("\"><img src=\"").Append(url).Append("\" alt=\"")
                .Append(WebUtility.HtmlEncode(label + " " + Path.GetFileName(relativePath))).Append("\"></a></div>");
        }

        private sealed class Result
        {
            public string Name, Mode;
            public long OriginalBytes, ResultBytes;
            public int ChangedPixels, TotalPixels;
            public double Milliseconds;
            public double SavingsPercent => 100.0 * (OriginalBytes - ResultBytes) / OriginalBytes;
        }
    }
}
